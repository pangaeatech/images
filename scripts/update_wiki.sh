#!/bin/bash
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB="${RM_LIB_DIR:-$HERE/lib}"
# shellcheck source=lib/common.sh
. "$LIB/common.sh"
# shellcheck source=lib/platform.sh
. "$LIB/platform.sh"

# Writes a file's contents to a Redmine wiki page.
# Usage: update_wiki.sh [FILE] [PAGE]
#   FILE default: wiki.markdown      PAGE default: Renovate_<project name>
# Env: RM_URL REDMINE_TOKEN RM_PROJECT_ID [WIKI_COMMENT]; project name from
#      PROJECT_NAME, CI_PROJECT_NAME or GITHUB_REPOSITORY.

file="${1:-${WIKI_FILE:-wiki.markdown}}"
rm_init
require_vars RM_PROJECT_ID
[ -f "$file" ] || die "Wiki file '$file' not found"
name="${PROJECT_NAME:-${CI_PROJECT_NAME:-${GITHUB_REPOSITORY:-}}}"
name="${name##*/}"
page="${2:-${WIKI_PAGE:-Renovate_${name}}}"
[ "$page" != "Renovate_" ] || die "No page name given and no project name available"

$JQ -n --rawfile text "$file" --arg comments "${WIKI_COMMENT:-Autogenerated from Dependency Dashboard}" \
  '{wiki_page:{text:$text,comments:$comments}}' | rm_send PUT "projects/${RM_PROJECT_ID}/wiki/${page}.json"
